    function getPath(obj, path) {
        return path.split('.').reduce((value, key) => value && value[key], obj);
    }

    function createI18n(initialLanguage) {
        const language = Vue.ref(initialLanguage);

        function setLanguage(nextLanguage) {
            language.value = nextLanguage in messages ? nextLanguage : 'zh';
            localStorage.setItem('pgvz-gui-language', language.value);
            document.documentElement.lang = language.value === 'zh' ? 'zh-CN' : 'en';
            document.title = getPath(messages[language.value], 'app.title');
        }

        function t(path) {
            return getPath(messages[language.value], path) || getPath(messages.zh, path) || path;
        }

        function optionLabel(key) {
            return getPath(messages[language.value], `options.${key}`) || key;
        }

        setLanguage(initialLanguage);

        return {
            language,
            setLanguage,
            t,
            optionLabel,
        };
    }

    return {
        createI18n,
    };
